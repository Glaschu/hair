-- Phase 1 booking store.
--
-- Everything here is either a time or an envelope the server cannot open.
-- No client name, number, email or note is ever stored in readable form.

CREATE TABLE IF NOT EXISTS salon (
  id          TEXT PRIMARY KEY,          -- always 'me': one salon, her use case
  name        TEXT NOT NULL,
  public_key  TEXT NOT NULL,             -- her sealing key; the secret half stays on her devices
  policy      TEXT,                      -- cancellation terms, shown before anyone can book
  updated_at  INTEGER NOT NULL
);

-- The key her devices carry. Minted by the setup page on first sign-in and
-- rotated when she starts over, so nobody has to set or remember a secret.
CREATE TABLE IF NOT EXISTS service (
  id          TEXT PRIMARY KEY,          -- always 'me'
  device_key  TEXT NOT NULL,
  rotated_at  INTEGER NOT NULL
);

-- Cancellation terms, immutable and content-addressed. A link pins the policy
-- it was minted under, so editing the wording later can never rewrite what a
-- client already agreed to -- which is the only thing that wins a chargeback.
CREATE TABLE IF NOT EXISTS policies (
  id         TEXT PRIMARY KEY,           -- sha-256 of the text, hex
  text       TEXT NOT NULL,
  -- The refund tiers the words describe, stored alongside them. A policy whose
  -- prose says 48 hours and whose maths says 24 only surfaces in an argument.
  tiers      TEXT,
  created_at INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS links (
  token         TEXT PRIMARY KEY,        -- 128-bit random, unguessable
  client_ref    TEXT NOT NULL,           -- opaque; means something only inside iris
  greeting      TEXT,                    -- "Hi Sara" — a first name at most
  service_name  TEXT NOT NULL,
  duration_mins INTEGER NOT NULL,
  price_minor   INTEGER NOT NULL,        -- pence. Never a float: a 50% deposit on
                                         -- a float is a rounding argument.
  tz            TEXT NOT NULL DEFAULT 'Europe/London',  -- the zone the times mean
  policy_id     TEXT REFERENCES policies(id),           -- pinned at mint time
  created_at    INTEGER NOT NULL,
  expires_at    INTEGER NOT NULL,
  revoked       INTEGER NOT NULL DEFAULT 0,
  -- One link, one booking, unless she deliberately minted a reusable one. A
  -- forwarded link should not be able to take her whole week.
  max_bookings  INTEGER NOT NULL DEFAULT 1,
  booked_count  INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS slots (
  id         TEXT PRIMARY KEY,
  token      TEXT NOT NULL REFERENCES links(token) ON DELETE CASCADE,
  starts_at  TEXT NOT NULL,              -- ISO 8601
  ends_at    TEXT NOT NULL,
  taken      INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS slots_by_token ON slots(token);

CREATE TABLE IF NOT EXISTS bookings (
  id          TEXT PRIMARY KEY,
  token       TEXT NOT NULL,
  slot_id     TEXT NOT NULL,
  client_ref  TEXT NOT NULL,             -- which client card this belongs to, in iris
  sealed      TEXT NOT NULL,             -- the envelope: opaque here, readable only on her devices
  created_at  INTEGER NOT NULL,
  agreed_at   INTEGER,                   -- when they ticked the cancellation terms
  -- WHAT they agreed to. A timestamp alone points at whatever the wording says
  -- today, which is worthless the moment she edits it.
  agreed_policy_id TEXT,
  -- Generated by the page before the first attempt. A retry after a lost
  -- response returns the original booking instead of sending them to a second
  -- slot -- which, with a deposit attached, was two charges for one person.
  request_id  TEXT,
  -- The single authority on whether this booking is live. Freeing a slot is
  -- exactly what lets a stale write reinstate a dead appointment, so anything
  -- that would revive a booking consults this first.
  status      TEXT NOT NULL DEFAULT 'confirmed'
                CHECK (status IN ('confirmed','cancelled','no_show')),
  cancelled_at INTEGER,
  cancelled_by TEXT CHECK (cancelled_by IN ('client','salon')),
  -- Frozen at cancellation from SERVER time, never a device clock, and never
  -- recomputed: the tier that applied is a fact about that moment.
  notice_ms   INTEGER,
  refund_pct  INTEGER,
  -- Lets the client cancel their own booking without an account. Unguessable,
  -- and useless for anything else.
  cancel_token TEXT,
  seen_at     INTEGER                    -- set once iris has imported it
);
CREATE UNIQUE INDEX IF NOT EXISTS bookings_request ON bookings(token, request_id);
CREATE INDEX IF NOT EXISTS bookings_unseen ON bookings(seen_at);

-- Days she has blocked off: a holiday, a course, a day she is ill. Kept here so
-- every booking path can refuse them — including an hour freed by a client
-- cancelling, which would otherwise go straight back on offer. Replaced whole
-- by her device each time she changes them, so it is always her current list.
CREATE TABLE IF NOT EXISTS days_off (
  starts_at  TEXT NOT NULL,   -- ISO instant, inclusive
  ends_at    TEXT NOT NULL    -- ISO instant, exclusive
);
